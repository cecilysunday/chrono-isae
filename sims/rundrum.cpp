// Fill a rotating drum by reimporting the system generated by 'setdrum.'
// Then, rotate the drum at a constant angular velocity and record the motion
// of the particles.
// 
// Additional notes:
// - Gravity aligned with z-axis
// - Drum axis of rotation aligned with the y-axis and centered at the origin
// - The drum velocity in rad / s is provided as an input argument
// - A positive drum velocity rotates the drum counterclockwise about +y
// - Drum inner diameter = clength_x = clength_z
// - Drum inner width = clength_y
// - The cylindrical wall of the drum is made up of a ring of spheres
// - Walls have negetive ID numbers (ID < 0)
// - Particles have positive ID numbers (ID >= 0)
//
// TO DO:
// - Particle size in drum should be radius = cp.grad * 0.99
//
// =============================================================================

